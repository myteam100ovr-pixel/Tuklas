// Generates two Blade partials with INLINE svg, so nothing is loaded from a CDN at runtime.
//   resources/views/partials/tech-logos.blade.php     (brand logos, from the simple-icons package)
//   resources/views/partials/function-chips.blade.php (our own generic icons for system functions)
// Run:  node scripts/make-tech-logos.mjs
import { mkdirSync, writeFileSync } from 'node:fs';
import * as icons from 'simple-icons';

const out = 'resources/views/partials';
mkdirSync(out, { recursive: true });

/* ---------- 1. Technology logos ---------- */
// [display name, simple-icons export]
const tech = [
    ['Laravel', 'siLaravel'],
    ['PHP', 'siPhp'],
    ['Jetstream', 'siLaravel'],          // Jetstream is Laravel's own starter kit, so it uses the Laravel mark
    ['Livewire', 'siLivewire'],
    ['Blade', null],                     // no brand logo, so we draw a generic code icon
    ['JavaScript', 'siJavascript'],
    ['Alpine.js', 'siAlpinedotjs'],
    ['Vite', 'siVite'],
    ['Tailwind CSS', 'siTailwindcss'],
    ['MySQL', 'siMysql'],
    ['Resend', 'siResend'],
    ['Google Sign-In', 'siGoogle'],
    ['Facebook Login', 'siFacebook'],
];

const codeIcon = '<svg viewBox="0 0 24 24" fill="none" stroke="#f55ba8" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M8 7l-5 5 5 5M16 7l5 5-5 5M14 5l-4 14"/></svg>';

const techHtml = tech.map(([name, key]) => {
    let svg;
    if (key) {
        const ic = icons[key];
        if (!ic) throw new Error(`Missing icon export: ${key}`);
        svg = `<svg viewBox="0 0 24 24" fill="#${ic.hex}" aria-hidden="true"><path d="${ic.path}"/></svg>`;
    } else {
        svg = codeIcon;
    }
    return `<li class="tk">${svg}<span>${name}</span></li>`;
}).join('\n');

writeFileSync(`${out}/tech-logos.blade.php`, `{{-- Generated by scripts/make-tech-logos.mjs. Do not edit by hand. --}}\n${techHtml}\n`);

